import { writeFile } from 'node:fs/promises'

const USER_ID = '1737682330585838'
const LIMIT = 8
const OUTPUT_FILE = 'src/data/writing.ts'

interface JuejinArticle {
  article_id: string
  article_info: {
    ctime: string
    title: string
  }
  tags?: { tag_name?: string }[]
  category?: { category_name?: string }
}

interface JuejinResponse {
  err_no: number
  err_msg: string
  data: JuejinArticle[]
}

const dateParts = (timestamp: number) => {
  const date = new Date(timestamp * 1000)
  return {
    year: date.getUTCFullYear(),
    month: String(date.getUTCMonth() + 1).padStart(2, '0'),
    day: String(date.getUTCDate()).padStart(2, '0'),
  }
}

const month = (timestamp: number) => {
  const { year, month } = dateParts(timestamp)
  return `${year}.${month}`
}

const day = (timestamp: number) => {
  const { year, month, day } = dateParts(timestamp)
  return `${year}.${month}.${day}`
}

const response = await fetch('https://api.juejin.cn/content_api/v1/article/query_list', {
  method: 'POST',
  headers: {
    'Content-Type': 'application/json',
    'User-Agent': 'Mozilla/5.0',
  },
  body: JSON.stringify({ user_id: USER_ID, cursor: '0', sort_type: 2 }),
})

if (!response.ok) {
  throw new Error(`Juejin API returned ${response.status}`)
}

const payload = (await response.json()) as JuejinResponse
if (payload.err_no !== 0) {
  throw new Error(`Juejin API error: ${payload.err_msg}`)
}

const writing = payload.data.slice(0, LIMIT).map((item) => ({
  title: item.article_info.title,
  platform: '掘金',
  date: month(Number(item.article_info.ctime)),
  tag: item.tags?.[0]?.tag_name ?? item.category?.category_name ?? '前端',
  href: `https://juejin.cn/post/${item.article_id}`,
}))

const syncedAt = day(Math.floor(Date.now() / 1000))
const output = `// Generated by scripts/sync-juejin.ts — do not edit by hand.
export interface WritingItem {
  title: string
  platform: string
  date: string
  tag: string
  href: string
}

export const writingSyncedAt = ${JSON.stringify(syncedAt)}

export const writing: WritingItem[] = ${JSON.stringify(writing, null, 2)}
`

await writeFile(OUTPUT_FILE, output, 'utf8')
await Bun.$`biome format --write ${OUTPUT_FILE}`.quiet()
console.log(`Wrote ${writing.length} articles to ${OUTPUT_FILE}`)
